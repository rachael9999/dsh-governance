GARBAGE_NAMES = {"HIGH", "CRITICAL", "MEDIUM"}


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        rows = list(reader)
    header = rows[0]
    data = rows[1:]

    out_rows = [header]
    dropped = 0
    missing = 0
    for r in data:
        if len(r) < 5:
            # 残缺行，丢弃
            dropped += 1
            continue
        node_id, node_type, name, desc, meta = r[0], r[1], r[2], r[3], r[4]
        # 丢弃损坏行：name 是严重度标记（属 riskMapping 误入 nodes）
        if name in GARBAGE_NAMES:
            dropped += 1
            continue
        new_desc = DESC.get(node_id)
        if new_desc is None:
            # 未覆盖的真实节点，保留原文并告警
            missing += 1
            print(f"  [WARN] 未覆盖 node_id: {node_id} (name={name})，保留原描述")
            new_desc = desc
        out_rows.append([node_id, node_type, name, new_desc, meta])

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        w.writerows(out_rows)

    print(f"完成：写入 {len(out_rows)-1} 个节点，丢弃损坏行 {dropped} 个，未覆盖 {missing} 个")
    print(f"输出文件：{OUT}")


if __name__ == "__main__":
    main()
